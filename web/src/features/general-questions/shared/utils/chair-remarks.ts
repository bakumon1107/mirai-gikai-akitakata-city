/**
 * 議長の発言のうち、議事進行の定型句だけのものを判別する。
 *
 * 議長のターンは議事録の約半分を占めるが、そのほとんどが
 * 「答弁を求めます。」「以上で答弁を終わります。」「○○議員。」といった
 * 進行上の決まり文句で、読み手にとっては意味を持たない。
 * 一方で「傍聴者の皆様に申し上げます…」「通告どおりにお願いします」のような
 * 実質的な発言は、前後のやり取りを理解するのに必要になる。
 */

// 先頭から繰り返し取り除く議事進行の定型句
const PROCEDURAL_PATTERNS: RegExp[] = [
  /^日程第[0-9０-９]{1,2}[、，]?[^。]{0,20}を行います。/,
  /^ただいまの質問に対し、?答弁を求めます。/,
  /^答弁を求めます。/,
  /^以上で、?答弁を終わります。/,
  /^答弁を終わります。/,
  /^以上で、?[^。]{0,20}の質問を終わります。/,
  /^以上で、?本日の日程は(?:全て)?終了いたしました。/,
  /^次回は[^。]{0,30}に再開いたします。/,
  /^本日は、?これにて散会いたします。/,
  /^続いて、?通告がありますので、?発言を(?:許します|許可します)。/,
  /^休憩を閉じ[てで]、?会議を再開(?:いたします|します)。/,
  /^[^。]{0,40}休憩と(?:いたします|します)。/,
  /^暫時休憩と(?:いたします|します)。/,
  /^[～~]+/,
  /^◯(?=[～~])/,
  /^午[前後][０-９0-9]{1,2}時[０-９0-9]{1,2}分(?:休憩|再開|散会|開議)/,
  /^[0-9０-９]{1,2}時間?が経過しましたので、?/,
  /^引き続き、?質問をお願いいたします。/,
  /^引き続き、?/,
  // 会議録末尾の署名欄
  /^地方自治法第[^。]{0,40}。/,
  /^安芸高田市議会(?:議長|議員)/,
  // 次の発言者の指名（"藤本市長。" "8番、新田議員。"）
  /^(?:[0-9０-９]{1,2}番[、，]?)?[^。、]{1,12}(?:議員|委員|市長|議長|部長|次長|課長|教育長|局長|委員長|参事|職務代理者|統括監)。/,
];

// 定型句を取り除いた残りがこの文字数未満なら、実質的な中身はないとみなす
const SUBSTANTIVE_MIN_LENGTH = 10;

/** 議事進行の定型句を先頭から取り除いた残りを返す（空白は除去済み） */
export function stripProceduralPhrases(text: string): string {
  let rest = text.replace(/\s/g, "");
  let changed = true;
  while (changed) {
    changed = false;
    for (const pattern of PROCEDURAL_PATTERNS) {
      const next = rest.replace(pattern, "");
      if (next !== rest) {
        rest = next;
        changed = true;
      }
    }
  }
  return rest;
}

/** 議長の発言に読む価値のある中身があるか */
export function isSubstantiveChairRemark(text: string): boolean {
  return stripProceduralPhrases(text).length >= SUBSTANTIVE_MIN_LENGTH;
}
